import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import test from "node:test";
import { tenantDatabase, asUser } from "./helpers/database";
test("sync leases publish private content through existing checkpoints and disconnect fences pending workers", async () => {
  const db = await tenantDatabase();
  const service = () => db.exec("reset role;set role service_role");
  try {
    const owner = randomUUID(), member = randomUUID(), other = randomUUID(), connection = randomUUID();
    await db.query("insert into auth.users(id) values($1),($2),($3)", [owner, member, other]);
    await asUser(db, owner);
    const org = (await db.query<{ id: string }>("select create_workspace('Connected company','Other') id")).rows[0].id;
    await db.exec("reset role");
    await db.query("insert into organization_members(organization_id,user_id,role) values($1,$2,'member')", [org, member]);
    await service();
    await db.query("select create_integration($1,$2,$3,'custom-api','Personal policies','{}','private','ciphertext')", [org, member, connection]);
    await db.query("select configure_integration($1,$2,$3,'selections',$4)", [connection, org, member, JSON.stringify({ items: [{ id: "policy", name: "Policy", kind: "document" }] })]);
    const claim = async () => (await db.query<{ result: { connection: { lease: string }; task: { id: string } } | null }>("select claim_integration($1) result", [connection])).rows[0].result;
    const first = (await claim())!;
    assert.equal(await claim(), null);
    const doc = randomUUID(), rev = randomUUID(), path = `organizations/${org}/documents/${doc}/${rev}/source.md`;
    const step = (lease: string, task: string, action: string, data: object = {}) => db.query<{ result: Record<string, unknown> }>("select integration_step($1,$2,$3,$4,$5) result", [connection, lease, task, action, JSON.stringify(data)]);
    await step(first.connection.lease, first.task.id, "prepare", { itemId: doc, revision: rev, name: "Private policy", url: "https://source.example/policy", path, size: 48, hash: "a".repeat(64), version: "v1", manifest: [{ content: "Personal policy allows 25 days of leave per year.", token_count: 15, start_offset: 0, end_offset: 48 }] });
    const second = (await claim())!;
    assert.equal((await step(second.connection.lease, second.task.id, "claim-index")).rows[0].result.claimed, true);
    await step(second.connection.lease, second.task.id, "checkpoint", { offset: 0, vectors: [[1, ...Array(1023).fill(0)]] });
    await claim();
    await asUser(db, member);
    assert.equal((await db.query("select * from search_knowledge('personal leave',null,24)")).rows.length, 1);
    assert.equal((await db.query("select * from search_knowledge('personal leave',null,24,null,array['uploads'])")).rows.length, 0);
    assert.equal((await db.query("select * from search_knowledge('personal leave',null,24,null,array['custom-api'])")).rows.length, 1);
    assert.equal((await db.query("select * from search_knowledge('personal leave',null,24,array[$1::uuid],null)", [randomUUID()])).rows.length, 0);
    const metadata = (await db.query<{ source_url: string }>("select * from knowledge_source_metadata(array[$1::uuid])", [doc])).rows[0];
    assert.equal(metadata.source_url, "https://source.example/policy");
    const chat = randomUUID();
    await db.query("select begin_filtered_chat_request($1,null,'What is the leave policy?',$2)", [chat, '{"platforms":["custom-api"]}']);
    await assert.rejects(db.query("select begin_filtered_chat_request($1,null,'What is the leave policy?',$2)", [chat, '{"platforms":["uploads"]}']), /mismatch/);
    await assert.rejects(db.query("select claim_integration(null)"), /permission denied/);
    await asUser(db, owner);
    assert.equal((await db.query("select * from documents where id=$1", [doc])).rows.length, 0);
    assert.equal((await db.query("select * from document_chunks")).rows.length, 0);
    assert.equal((await db.query<{ allowed: boolean }>("select private.can_read_integration_file($1) allowed", [path])).rows[0].allowed, false);
    await service();
    await assert.rejects(db.query("select configure_integration($1,$2,$3,'settings',$4)", [connection, org, member, '{"visibility":"workspace"}']), /owners/);
    await db.query("select configure_integration($1,$2,$3,'selections',$4)", [connection, org, member, JSON.stringify({ items: [{ id: "policy", name: "Policy", kind: "document" }, { id: "unreadable", name: "Unsupported binary", kind: "document" }] })]);
    for (let n = 0; n < 2; n++) {
      const selected = (await claim())!;
      await step(selected.connection.lease, selected.task.id, "rejected", { error: "This file is not supported text." });
    }
    await claim();
    assert.equal((await db.query("select * from integration_tasks where not done")).rows.length, 0);
    assert.equal((await db.query("select * from integration_items where last_error is not null")).rows.length, 2);
    await asUser(db, member);
    assert.equal((await db.query("select * from search_knowledge('personal leave',null,24)")).rows.length, 0);
    await service();
    await db.query("select configure_integration($1,$2,$3,'sync')", [connection, org, member]);
    const pending = (await claim())!;
    await db.query("select configure_integration($1,$2,$3,'disconnect')", [connection, org, member]);
    await assert.rejects(step(pending.connection.lease, pending.task.id, "unchanged", { name: "Policy", version: "v1" }), /lease expired/);
    await assert.rejects(db.query("select save_integration_credential($1,'new-token')", [connection]), /disconnected/);
    assert.equal((await db.query("select * from integration_credentials")).rows.length, 0);
    assert.equal((await db.query("select * from integration_file_gc")).rows.length, 1);
    await asUser(db, member);
    assert.equal((await db.query("select * from search_knowledge('personal leave',null,24)")).rows.length, 0);
    assert.equal((await db.query<{ allowed: boolean }>("select private.can_read_integration_file($1) allowed", [path])).rows[0].allowed, false);
  } finally { await db.close(); }
});
